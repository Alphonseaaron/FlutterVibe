void main() async {
  const env = String.fromEnvironment('ENV', defaultValue: 'dev');
  WidgetsFlutterBinding.ensureInitialized();
  await ConfigService.load(env);
  await Firebase.initializeApp();
  Stripe.publishableKey = 'pk_test_51H...';
  await initHive();
  await initSyncService();
  await LocationService.init();
  final authService = AuthService();
  await authService.checkAuth();
  final localizationService = LocalizationService();
  await localizationService.load();
  final featureFlagService = FeatureFlagService();
  await featureFlagService.load();
  final versionService = VersionService();
  await versionService.init();
  final onboardingComplete = await OnboardingController.isOnboardingComplete();
  WidgetsBinding.instance.addObserver(LifecycleService());
  final pushNotificationService = PushNotificationService();
  await pushNotificationService.init();
  final dynamicLinkService = DynamicLinkService();
  await dynamicLinkService.init();
  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider<AuthService>.value(
          value: authService,
        ),
        ChangeNotifierProvider<LocalizationService>.value(
          value: localizationService,
        ),
        ChangeNotifierProvider<FeatureFlagService>.value(
          value: featureFlagService,
        ),
        ChangeNotifierProvider<VersionService>.value(
          value: versionService,
        ),
        ChangeNotifierProvider<LoadingService>(
          create: (_) => LoadingService(),
        ),
        ChangeNotifierProvider<PageTitleService>(
          create: (_) => PageTitleService(),
        ),
        ChangeNotifierProvider<MotionService>(
          create: (_) => MotionService(),
        ),
        ChangeNotifierProvider<FileUploadService>(
          create: (_) => FileUploadService(),
        ),
        ChangeNotifierProvider<PromoCodeService>(
          create: (_) => PromoCodeService(),
        ),
      ],
      child: App(onboardingComplete: onboardingComplete),
    ),
  );
}
